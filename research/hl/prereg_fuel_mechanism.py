MIN_SNAPSHOTS = None   # 同上：要多少輪才判，取決於量出來的 SE，不是猜的


# ===========================================================================
# 自曝檢查（每一關都要看到它綠一次、也紅一次，否則不知道它有沒有在測量）
# ===========================================================================
def g1_geometry(pos: pd.DataFrame) -> dict:
    """多單清算價必在 mark 之下、空單之上。違反數必須是 0。

    這一關錄製器每小時已經在跑（hl_fuel_recorder 的 flag 帶 geometry 違反數），
    這裡重跑一次是因為**分析端用的是 parquet、錄製端用的是 API 回應**，
    兩者之間有一層寫入（mistake.md 2026-08-29：一份資料兩個讀者只改了一個）。
    """
    d = pos.dropna(subset=["liq_px", "mark"])
    d = d[(d.liq_px > 0) & (d.mark > 0)]
    long_bad = int(((d.szi > 0) & (d.liq_px >= d.mark)).sum())
    short_bad = int(((d.szi < 0) & (d.liq_px <= d.mark)).sum())
    return dict(ok=(long_bad == 0 and short_bad == 0),
                long_bad=long_bad, short_bad=short_bad, n=int(len(d)))


def g5_distribution(f_vals) -> dict:
    """F 的分布不能退化：任何桶為 0 或佔比 >90% 一律先當儀器壞掉。

    mistake.md 2026-08-02：D4 的 swing 桶 n=0，原因是記帳細節不是市場。
    先看 n 的分布合不合物理，再看效應。
    """
    f = np.asarray(f_vals, float)
    f = f[np.isfinite(f)]
    if len(f) < 20:
        return dict(ok=False, reason="樣本太少，還不能判分布", n=int(len(f)))
    q = np.percentile(f, [0, 25, 50, 75, 100])
    top = float((f == f.max()).mean())
    zero = float((f == 0).mean())
    return dict(ok=(top < 0.9 and zero < 0.9), n=int(len(f)),
                quartiles=[round(float(x), 6) for x in q],
                frac_at_max=round(top, 4), frac_zero=round(zero, 4))


# ===========================================================================
# 判決（在門檻被凍結之前，這裡拒絕產生任何東西）
# ===========================================================================
def verdict(*_a, **_kw):
    """刻意 fail-closed。

    沒有門檻就沒有判決。這個 raise 是設計不是未完成 —— 它擋的是
    「先看數字再寫門檻」，而那正是整份預註冊存在的理由。
    """
    if THRESHOLDS is None or MIN_SNAPSHOTS is None:
        raise RuntimeError(
            "門檻還沒凍結。填 THRESHOLDS / MIN_SNAPSHOTS 之前不得產生判決。\n"
            "填之前要做的事，依序：\n"
            "  1. 累積資料（凍結日只有 3 輪逐部位快照）\n"
            "  2. 用 harness.boot_days 對**真實標籤**算 SE（不准手算、\n"
            "     不准在置換資料上算 —— mistake.md 2026-09-06 低估 9 倍）\n"
            "  3. 門檻寫在 CI 上不寫在點估計上（mistake.md 2026-09-04）\n"
            "  4. 寫完立刻把當時數字代進去：現在就過、或不可能不過 -> 不是門檻\n"
            "  5. SE >= 門檻 => 這個設計不能做決定，回去重新設計")
    raise NotImplementedError("門檻已填，請接上計分器")


