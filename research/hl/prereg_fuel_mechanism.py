#   THRESHOLDS = dict(
#       ci_low_gt=...,        # 主臂日聚類 CI 下緣必須 > 這個值
#       coins_pos_min=...,    # 逐幣同號的最低比例
#       control_must_contain_zero=True,    # 對照臂（後方密度）必須含零
#       coverage_monotone=True,            # 效應不得隨覆蓋率上升而減弱
