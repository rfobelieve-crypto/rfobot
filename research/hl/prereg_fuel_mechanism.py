STOP_CONDITIONS = """
- 對照臂（後方密度）顯著 -> 儀器壞了，主臂不得報告，先修儀器。
- F 的分布退化（G5 紅）-> 先查儀器，不解讀。
- 效應隨覆蓋率上升而**減弱** -> 與真效應的方向相反，判為測量假象。
- SE >= 門檻 -> 無效判決（inconclusive by design），**不是 FAIL**，
  重新設計再開跑。地形扳機就是這樣結案的，那不是「測過而且輸了」。
"""


def inventory():
    """凍結日的資料清冊 —— 寫下來是為了證明寫這份註冊時還沒有答案可看。"""
    snaps = sorted(glob.glob(str(POS / "*.parquet")))
    mkts = sorted(glob.glob(str(MKT / "*.json")))
    n_rows = 0
    g1 = None
    if snaps:
        d = pd.read_parquet(snaps[-1])
        n_rows = int(len(d))
        g1 = g1_geometry(d)
    return dict(snapshots=len(snaps), market_rounds=len(mkts),
                last_snapshot_rows=n_rows, g1_geometry=g1,
                thresholds_frozen=THRESHOLDS is not None)


