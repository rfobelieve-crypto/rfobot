"""Which cells belong in `home_regime`? — TODO §0.59b.

Product side asked (產品端詢問_主場定義是否納入TREND_DOWN_20260826.md) why
§0.59's filter keeps only RANGING when TREND_DOWN's forward meanR is higher.
They refused to change it themselves and asked for a ruling. Correct call.

THE HONEST BACKGROUND, stated first because it changes who bears the burden
of proof: §0.59 was generated by the §0.58 decomposition, whose criterion
was "which cells held between two non-overlapping samples". Applied to the
table it produced, that criterion selects TWO cells, not one. RANGING-only
was a carry-over from the UNDIRECTED framing of the survival layer (§0.49:
ADX RANGING vs TRENDING) — the very simplification §0.54b already overturned
on this line. So this is not a post-hoc widening on new evidence; it is the
original criterion applied without the leftover.

Consequently the numbers in the product side's t-table are NOT used to
decide. They were computed after looking at the forward sample; leaning on
them would be exactly the C/D trap. The decision runs on §0.58's two-sample
consistency, which predates that table.

CRITERION, frozen before running (a cell joins home_regime iff ALL hold):
  C1  meanR > 0 in BOTH non-overlapping samples (backtest pre-FREEZE and
      forward post-FREEZE). Sign consistency across independent samples is
      the whole basis of §0.58's reading; nothing weaker qualifies.
  C2  per-coin breadth >= 5/9 in the BACKTEST sample. Breadth is only
      demanded of the large sample — the forward one is too thin to carry
      it, and demanding it there would silently select on noise.
  C3  day-clustered CI low > 0 in the BACKTEST sample. Same reasoning: the
      forward sample cannot support an interval test, so it is not asked to.

FALSIFICATION, also pre-stated. If TREND_DOWN passes C1-C3 its forward
result must additionally not be an artefact of one coin or a few days:
  F1  no single coin contributes > 50% of the forward cell's total R
  F2  no single UTC day contributes > 50% of it
A cell that passes C1-C3 but fails F1/F2 is reported as PASSES-BUT-FRAGILE
and the ruling says so rather than hiding it.

SENSITIVITY is reported unconditionally: what the union's forward meanR
would be if the added cell were truly worth zero. If the union still beats
a plausible alternative under that assumption, the decision is robust to
being wrong about the added cell — which matters more than the point
estimate, because n is small.

Read-only. Decides a DEFINITION, scores no gate.
"""
