from pathlib import Path

from docx import Document
from docx.oxml.ns import qn
from docx.shared import Pt

OUT = Path.home() / "Desktop" / "linkedin_posts" / "quant_ep8_confidence-intervals.docx"

BODY = """信賴區間不是拿來宣告勝利的

同一個工具，我在同一個專案上錯了五次。每一次錯的都不是計算，是「它在回答哪個問題」。

大多數人看信賴區間只做一件事：看它有沒有跨過零。跨過就是沒結論，沒跨過就是有發現。那是這個工具能給你的資訊裡，最少的一份。

下面五個都是我自己犯的，全部有紀錄可查。

錯法一：把門檻寫在對自己有利的那一端

我要主張「某一組的表現比全體差」，判準寫成：該組的信賴區間下緣要低於全體。我還在括號裡特地註明，這比只看點估計嚴格。

寫完之後把現有數字代進去：該組區間是 37.3 到 59.0，全體 59.3。下緣 37.3 當然低於 59.3。

任何夠寬的區間都自動滿足它。那不是門檻，是一句恆真句。

真正讓這個發現勉強站住的是上緣：59.0 小於 59.3，只贏 0.3 個百分點。而我在同一份文件的另一段，自己寫過這句話。

方向性的主張，門檻要壓在對自己有利的那一端。主張更差就壓上緣，主張更好就壓下緣。壓錯邊，門檻就失效了。

錯法二：門檻比雜訊還小

一個功能要不要上線，我設了個扳機：兩組的差要達到 8 個百分點。

跑了一個月，差 5.8 個百分點，看起來像「差一點沒過」。

檢討的第一件事是把標準誤算出來。在那個樣本數下，兩個比例的差，標準誤是 11.6 個百分點。

門檻 8。雜訊 11.6。

這個設計不管資料怎麼走，都分辨不出過與不過。它不是快要過了，它是從註冊那天起就不可能有答案。要讓區間半寬壓進 8 個百分點，需要八倍樣本，以當時的頻率大約要兩年。

所以凍結任何判準的當下，除了把現有數字代進去，還要算它在你打算收集的樣本數下的標準誤。標準誤大於等於門檻，這個設計就不能做決定，必須先重新設計再開跑。

錯法三：標準誤自己算錯了九倍

學乖之後，下一個專案我在註冊時照規矩算了標準誤，得到 0.025，並在註冊書上寫「這個設計有測量能力」。

實測是 0.23。九倍。

三層原因，方向全部同向，全部讓我低估：

我用的變異數來自逐根 K 線的母體，但事件條件下的變異數是它的 1.7 倍。判決會用日聚類重抽，而事件在同一天、甚至同一根 K 線上高度重複，重複率四分之一。分位再分桶之後，每一臂只剩十二分之一的樣本。

最值得講的是：我當時做了對照跑。我把標籤打亂，在隨機資料上跑過整台判定機器，得到「都不顯著」，正確地驗證了機器沒有寫錯。

但打亂標籤恰好破壞掉「同一天的結果會一起動」這個結構，而那正是讓標準誤變大的來源。打亂之後日內互相獨立，聚類重抽對它給出天生偏窄的區間。

置換能驗機器有沒有寫錯，不能驗它有沒有功效。

標準誤要用判決真正會用的那台機器跑出來，不是用公式手算。

錯法四：拿「差值」的參考值去比「水準」

為了比較三種進場方式，我用了配對設計：三條路共用同一個出場，把市場路徑消掉。差值因此非常乾淨。

但為了讓配對成立，我刻意拿掉了災難停損（停損是相對進場價的，三個進場價會產生三個停損、三個出場，配對性就沒了）。

所以每一條路的「水準」量的已經是另一條規則。

我一度拿配對表的水準去宣稱「這條策略的天花板不顯著」。那是錯的。把停損加回去重算，天花板顯著為正。

而就在寫這篇的同一週，我又犯了一次：另一支程式的守衛，我拿一個配對「差值」當它「水準」的對照參考值，害那道守衛誤判失敗。

任何為了配對或控制而修改過規則的設計，它的「水準」不可引用。一張表裡同時出現差值和水準時，必須標明水準是用哪一套規則算的——因為容器長得一樣，語意不一樣。

錯法五：它只量抽樣，量不到你在量錯的東西

這是最貴的一個。

一條策略：每筆報酬的區間下緣穩穩大於零、九個標的全部同向、t 值超過 3。兩年半的資料，統計上沒有任何破綻。

換一個假設之後，同一批交易的區間上緣小於零。

換掉的不是統計方法。換掉的是成交價。

回測假設「在某個價位成交」。實測下來，超過半數的交易在下單那一刻，市場已經走過那個價位了；其中將近一半，成交那根 K 線從頭到尾沒有出現過那個價格。

信賴區間從頭到尾都算對。它量的是「如果重新抽一次樣本，這個平均會擺盪多少」。它不會、也不可能告訴你：你餵給它的那個平均，本身是用一個不存在的價格算出來的。

統計顯著永遠只能處理抽樣誤差。它處理不了資料污染、模型版本混合、或是一個拿不到的成交價。

信賴區間是最後一關，不是第一關。

三個要在看到數字之前就回答的問題

一、我的主張是哪個方向？門檻要壓在對我不利的那一端。

二、在我打算收集的樣本數下，標準誤是多少？它比我的門檻小嗎？如果不是，先重新設計，不要開跑。

三、這個區間底下的那個平均，是用可實現的假設算出來的嗎？

前兩個問完，你會少開很多註定沒有答案的專案。第三個問完，你會少宣布很多不存在的發現。

我這五次都是先做完才回頭發現的。寫下來，是希望下一次能在做之前就問。
"""


def main():
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = "Microsoft JhengHei"
    st.font.size = Pt(11)
    st._element.rPr.rFonts.set(qn("w:eastAsia"), "Microsoft JhengHei")
    for line in BODY.strip().split("\n"):
        doc.add_paragraph(line.strip())
    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUT)
    n = len([x for x in BODY.strip().split("\n") if x.strip()])
    print(f"written -> {OUT}")
    print(f"段落 {n}、字數約 {len(BODY.replace(chr(10), ''))}")


if __name__ == "__main__":
    main()
